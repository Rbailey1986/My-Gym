// Builds src/lib/foods-data.js from catalogue/foods/{crea,cofid}.csv. Run: node scripts/foods-build.mjs
// Values are per 100 g of the food as listed: k kcal, p protein, f fat, c carbs, s sugars, fi fibre (g), na sodium (mg).
// CREA (Italian) rows come first so Italian foods win ties in search.
import { readFileSync, writeFileSync } from 'node:fs'

function csv(file) {
  const rows = []
  let row = [], cell = '', quoted = false
  for (const ch of readFileSync(new URL('../catalogue/foods/' + file, import.meta.url), 'utf8')) {
    if (quoted) { if (ch === '"') quoted = false; else cell += ch; continue }
    if (ch === '"') quoted = true
    else if (ch === ',') { row.push(cell); cell = '' }
    else if (ch === '\n') { row.push(cell); rows.push(row); row = []; cell = '' }
    else if (ch !== '\r') cell += ch
  }
  const [head, ...body] = rows
  return body.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])))
}
const n = v => v === '' || v == null ? undefined : Math.round(+v * 100) / 100
const entry = o => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined && v !== ''))

const foods = [
  ...csv('crea.csv').map(r => entry({ id: 'it-' + r.code, n: r.name, en: r.english, cat: r.category, src: 'it', pt: n(r.portion), k: n(r.kcal), p: n(r.protein), f: n(r.fat), c: n(r.carbs), s: n(r.sugars), fi: n(r.fibre), na: n(r.sodium) })),
  ...csv('cofid.csv').map(r => entry({ id: 'uk-' + r.code, n: r.name, src: 'uk', k: n(r.kcal), p: n(r.protein), f: n(r.fat), sf: n(r.satfat), c: n(r.carbs), s: n(r.sugars), fi: n(r.fibre), na: n(r.sodium) })),
].filter(x => x.k != null && x.p != null && x.f != null && x.c != null)

writeFileSync(new URL('../src/lib/foods-data.js', import.meta.url),
  '// generated by scripts/foods-build.mjs from catalogue/foods/ — do not edit\n// Sources: CREA Tabelle di composizione degli alimenti (it), McCance & Widdowson CoFID 2021 (uk, OGL v3.0)\nexport const FOODS=' + JSON.stringify(foods) + '\n')
