#!/usr/bin/env node
// The desktop build's exercise catalogue: only what can be done at home — body weight, dumbbells
// and bands — plus the treadmill, stationary/spin bike and rowing machine. Everything else is
// left out of the app entirely, data and media both. Writes:
//
//   frontend/src/desktop/generated/exercises-data.js   the app's catalogue (aliased over lib/exercises-data.js)
//   frontend/src/desktop/generated/library-data.js     the Coach's catalogue (aliased over api/coach/core/library-data.js)
//   frontend/src/desktop/generated/home-subs.js        starter-plan exercises → their closest kept stand-in
//   desktop/media-staged/{still,clip}/                 the pictures and animations of what is kept
//
// Run by build-frontend.mjs before the Vite build. The web and phone builds are untouched.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const at = (...p) => path.join(ROOT, ...p)
const load = p => import(pathToFileURL(at(p)).href)

const KEEP_EQUIPMENT = new Set(['body weight', 'dumbbell', 'band', 'resistance band'])
// Cardio machines the catalogue tags as something else ("leverage machine", or a treadmill
// filed under "stationary bike"), picked by name.
const MACHINE = /treadmill|stationary bike|bicycle recline|assault bike|rowing machine/i

const { EXDB, EXALIAS } = await load('frontend/src/lib/exercises-data.js')
const keep = e => KEEP_EQUIPMENT.has(e.eq) || MACHINE.test(e.n)
const kept = EXDB.filter(keep)
const keptIds = new Set(kept.map(e => e.id))
const aliases = Object.fromEntries(Object.entries(EXALIAS).filter(([, to]) => keptIds.has(to)))

const out = at('frontend/src/desktop/generated')
fs.mkdirSync(out, { recursive: true })
const header = '// generated by desktop/build-catalogue.mjs for the desktop build only — do not edit\n'
fs.writeFileSync(path.join(out, 'exercises-data.js'),
  header + 'export const EXDB=' + JSON.stringify(kept) + '\nexport const EXALIAS=' + JSON.stringify(aliases) + '\n')

const lib = await load('api/coach/core/library-data.js')
const coachKept = lib.EXERCISES.filter(e => keptIds.has(e.id))
fs.writeFileSync(path.join(out, 'library-data.js'),
  header + 'export const GENERATED_FROM = ' + JSON.stringify(lib.GENERATED_FROM ?? null) +
  ';\nexport const COUNT = ' + coachKept.length + ';\nexport const EXERCISES = ' + JSON.stringify(coachKept) + ';\n')

/* Starter plans name barbell and machine lifts. Each one that is gone gets its closest kept
   stand-in, scored the way lib/starter.js substituteFor() scores one: same body part, sharing a
   target, main or helper muscle; then target, main muscle, name and helper muscles; a loaded
   stand-in beats a body-weight drill for a loaded lift. Ported rather than imported because
   starter.js pulls in the whole browser app. */
const starterSrc = fs.readFileSync(at('frontend/src/lib/starter.js'), 'utf8')
const starterIds = [...new Set([...starterSrc.matchAll(/\['(\d{4,5})', \d+, \d+\]/g)].map(m => m[1]))]
const byId = Object.fromEntries(EXDB.map(e => [e.id, e]))
const NOT_A_LIFT = /stretch|isometric|squeeze|yoga|\bpose\b|toe touch|\broll(er)?\b|mobility|circles|warm-?up|boxing|against wall/i
const NEEDS_BALL = /exercise ball|stability ball|swiss ball|bosu/i
const EQ_WORDS = new Set([...new Set(EXDB.map(e => e.eq))].flatMap(e => e.split(/[^a-z0-9]+/)).concat(['lever', 'leverage', 'machine', 'sled']))
const words = ex => new Set(ex.n.toLowerCase().split(/[^a-z0-9]+/).filter(w => w && !EQ_WORDS.has(w)))
const jaccard = (a, b) => { const i = [...a].filter(x => b.has(x)).length; return i ? i / (a.size + b.size - i) : 0 }
const substitute = (ex, taken) => {
  const exWords = words(ex), exSm = new Set([ex.mg, ...(ex.sm || [])])
  const loaded = ex.eq !== 'body weight'
  let best = null, bestScore = -Infinity
  for (const c of kept) {
    if (c.bp !== ex.bp || taken.has(c.id) || MACHINE.test(c.n)) continue
    if (NOT_A_LIFT.test(c.n) || NEEDS_BALL.test(c.n)) continue
    const sm = jaccard(exSm, new Set([c.mg, ...(c.sm || [])]))
    if (c.tg !== ex.tg && c.mg !== ex.mg && !sm) continue
    const score = 2 * (c.tg === ex.tg) + (c.mg === ex.mg) + 3 * jaccard(exWords, words(c)) + 2 * sm - (loaded && c.eq === 'body weight' ? 3 : 0)
    if (score > bestScore || (score === bestScore && c.id < best.id)) { best = c; bestScore = score }
  }
  return best
}
const subs = {}
const taken = new Set(starterIds.filter(id => keptIds.has(id)))
for (const id of starterIds) {
  if (keptIds.has(id) || !byId[id]) continue
  const s = substitute(byId[id], taken)
  subs[id] = s ? s.id : null
  if (s) taken.add(s.id)
}
fs.writeFileSync(path.join(out, 'home-subs.js'), header + 'export const HOME_SUBS = ' + JSON.stringify(subs) + '\n')

// Media: each kept exercise's own files, and its female-figure variant's (`fv`).
const media = at('catalogue/media'), staged = at('desktop/media-staged')
fs.rmSync(staged, { recursive: true, force: true })
let copied = 0
for (const dir of ['still', 'clip']) {
  fs.mkdirSync(path.join(staged, dir), { recursive: true })
  const ext = dir === 'still' ? '.webp' : '.mp4'
  for (const e of kept) {
    for (const id of [e.id, e.fv].filter(Boolean)) {
      const src = path.join(media, dir, id + ext)
      if (fs.existsSync(src)) { fs.copyFileSync(src, path.join(staged, dir, id + ext)); copied++ }
    }
  }
}
fs.copyFileSync(path.join(media, 'NOTICE.md'), path.join(staged, 'NOTICE.md'))

console.log(`catalogue: kept ${kept.length} of ${EXDB.length} exercises (${Object.keys(aliases).length} aliases), coach ${coachKept.length}, ${copied} media files`)
for (const [from, to] of Object.entries(subs)) console.log(`  starter ${from} ${byId[from].n} -> ${to ? to + ' ' + byId[to].n : '(dropped)'}`)
